object Strings {
 private val placeholder=Regex("\\{([a-z]+)\\}")

 fun get(lang:Lang,msg:Msg):String=table.getValue(lang)[msg]?:table.getValue(Lang.EN).getValue(msg)

 fun render(lang:Lang,msg:Msg,args:Map<String,String> =emptyMap()):String=
  placeholder.replace(get(lang,msg)) { m->args[m.groupValues[1]]?:m.value }

 fun render(lang:Lang,alert:Alert)=render(lang,alert.msg,alert.args)

 fun amount(lang:Lang,won:Int)=render(lang,Msg.AMOUNT,mapOf("n" to Fines.format(won)))

 fun placeholders(text:String)=placeholder.findAll(text).map { it.groupValues[1] }.toSet()

 /** 테스트용: 언어별 누락 키. */
 fun missing(lang:Lang)=Msg.entries.filter { it !in table.getValue(lang) }

 private val table:Map<Lang,Map<Msg,String>> by lazy {
  Lang.entries.associateWith { l->base[l].orEmpty()+RuleStrings.table[l].orEmpty()+EuroStrings.table[l].orEmpty() }
 }

